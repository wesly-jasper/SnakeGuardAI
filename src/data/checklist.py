"""Write a human verification checklist for the knowledge tables.

    python -m src.data.checklist            # writes docs/verification_checklist.md

Groups every unverified numeric row by citation key, so a reviewer can open one PDF and
check all its numbers. After checking a row against the PDF, set `verified=true` in the CSV
(and fix the number if needed), then re-run this command.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from src.data.knowledge import load_knowledge, split_keys

REPO_ROOT = Path(__file__).resolve().parents[2]


def unverified_rows(knowledge_dir: Path) -> pd.DataFrame:
    """All unverified rows with a number, as (source_key, table, item, value, evidence)."""
    kb = load_knowledge(knowledge_dir, allow_missing_onset=True)
    species = kb.species[(kb.species["group"] == "venomous") & kb.species["dry_bite_rate"].notna()]
    parts = [
        species.assign(table="species.csv", item=species["species"] + " / dry_bite_rate",
                       value=species["dry_bite_rate"].map(str)),
        kb.clinical.assign(
            table="clinical_table.csv",
            item=kb.clinical["species"] + " / " + kb.clinical["symptom"],
            value=kb.clinical.apply(
                lambda r: f"freq {r.frequency}, onset {r.onset_min_hours}-{r.onset_max_hours} h", axis=1
            ),
        ),
        kb.context.assign(table="context_table.csv", item=kb.context["species"] + " / " + kb.context["feature"],
                          value=kb.context["probability"].map(str)),
    ]
    rows = pd.concat([p[~p["verified"]][["source_key", "table", "item", "value", "evidence"]] for p in parts])
    rows = rows.assign(source=rows["source_key"].map(lambda k: (split_keys(k) or ["(none)"])[0]))
    return rows.sort_values(["source", "table", "item"]).reset_index(drop=True)


def render(rows: pd.DataFrame) -> str:
    lines = [
        "# Knowledge-table verification checklist",
        "",
        "Generated by `python -m src.data.checklist`. Each item is an AI-assisted extraction.",
        "Check it against the source PDF, correct the CSV if needed, then set `verified=true`.",
        f"Unverified rows: **{len(rows)}**.",
        "",
    ]
    for source, group in rows.groupby("source", sort=True):
        lines += [f"## {source} ({len(group)})", ""]
        for r in group.itertuples():
            lines.append(f"- [ ] `{r.table}` **{r.item}**: {r.value} (keys: {r.source_key}) — {r.evidence}")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--knowledge-dir", default=str(REPO_ROOT / "knowledge"))
    parser.add_argument("--out", default=str(REPO_ROOT / "docs" / "verification_checklist.md"))
    args = parser.parse_args(argv)
    rows = unverified_rows(Path(args.knowledge_dir))
    Path(args.out).write_text(render(rows), encoding="utf-8")
    print(f"wrote {len(rows)} unverified row(s) to {args.out}")


if __name__ == "__main__":
    main()
